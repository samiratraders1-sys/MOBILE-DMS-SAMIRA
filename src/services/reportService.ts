/**
 * Samira Traders DMS - Unified Report Export Service (CSV, Excel, PDF)
 * Prevents button conflicts and normalizes data export formatting.
 */

export function exportToCSV(filename: string, headers: string[], rows: (string | number)[][]): void {
  try {
    const csvContent = [
      headers.map(h => `"${String(h).replace(/"/g, '""')}"`).join(","),
      ...rows.map(row => row.map(cell => `"${String(cell ?? "").replace(/"/g, '""')}"`).join(","))
    ].join("\r\n");

    const blob = new Blob(["\ufeff" + csvContent], { type: "text/csv;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.setAttribute("download", filename.endsWith(".csv") ? filename : `${filename}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  } catch (error) {
    console.error("CSV Export Error:", error);
  }
}

export function exportToExcel(filename: string, headers: string[], rows: (string | number)[][]): void {
  try {
    const tableHeader = headers.map(h => `<th style="background-color:#0f172a;color:#ffffff;padding:8px;border:1px solid #ddd;">${h}</th>`).join("");
    const tableRows = rows
      .map(row => `<tr>${row.map(cell => `<td style="padding:8px;border:1px solid #ddd;">${cell ?? ""}</td>`).join("")}</tr>`)
      .join("");

    const htmlTable = `
      <html xmlns:o="urn:schemas-microsoft-com:office:office" xmlns:x="urn:schemas-microsoft-com:office:excel" xmlns="http://www.w3.org/TR/REC-html40">
        <head>
          <meta charset="utf-8" />
          <!--[if gte mso 9]>
          <xml>
            <x:ExcelWorkbook>
              <x:ExcelWorksheets>
                <x:ExcelWorksheet>
                  <x:Name>Report</x:Name>
                  <x:WorksheetOptions><x:DisplayGridlines/></x:WorksheetOptions>
                </x:ExcelWorksheet>
              </x:ExcelWorksheets>
            </x:ExcelWorkbook>
          </xml>
          <![endif]-->
        </head>
        <body>
          <table border="1">
            <thead><tr>${tableHeader}</tr></thead>
            <tbody>${tableRows}</tbody>
          </table>
        </body>
      </html>
    `;

    const blob = new Blob([htmlTable], { type: "application/vnd.ms-excel;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.setAttribute("download", filename.endsWith(".xls") ? filename : `${filename}.xls`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  } catch (error) {
    console.error("Excel Export Error:", error);
  }
}

export function exportToPDF(title: string, headers: string[], rows: (string | number)[][], filename?: string): void {
  try {
    const printWindow = window.open("", "_blank");
    if (!printWindow) {
      alert("পপ-আপ উইন্ডো অবরুদ্ধ। অনুগ্রহ করে ব্রাউজারের পপ-আপ অনুমতি দিন।");
      return;
    }

    const todayStr = new Date().toLocaleDateString("bn-BD");

    const htmlContent = `
      <!DOCTYPE html>
      <html>
        <head>
          <title>${title}</title>
          <style>
            body { font-family: 'Segoe UI', Tahoma, Geneva, Verdana, sans-serif; padding: 20px; color: #1e293b; }
            .header { text-align: center; margin-bottom: 20px; border-bottom: 2px solid #0f172a; padding-bottom: 10px; }
            .header h1 { margin: 0; font-size: 22px; color: #0f172a; }
            .header p { margin: 5px 0 0 0; font-size: 13px; color: #64748b; }
            table { width: 100%; border-collapse: collapse; margin-top: 15px; font-size: 12px; }
            th { background-color: #0f172a; color: #ffffff; padding: 8px 12px; text-align: left; font-weight: 600; }
            td { padding: 8px 12px; border-bottom: 1px solid #e2e8f0; }
            tr:nth-child(even) { background-color: #f8fafc; }
            .footer { margin-top: 30px; text-align: right; font-size: 11px; color: #94a3b8; }
          </style>
        </head>
        <body>
          <div class="header">
            <h1>সামিরা ট্রেডার্স - ${title}</h1>
            <p>তারিখ: ${todayStr}</p>
          </div>
          <table>
            <thead>
              <tr>${headers.map(h => `<th>${h}</th>`).join("")}</tr>
            </thead>
            <tbody>
              ${rows.map(row => `<tr>${row.map(cell => `<td>${cell ?? ""}</td>`).join("")}</tr>`).join("")}
            </tbody>
          </table>
          <div class="footer">
            Generated by Samira Traders DMS v2.1.0
          </div>
          <script>
            window.onload = function() {
              window.print();
            };
          </script>
        </body>
      </html>
    `;

    printWindow.document.write(htmlContent);
    printWindow.document.close();
  } catch (error) {
    console.error("PDF Export Error:", error);
  }
}
